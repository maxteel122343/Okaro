/**
 * Hardware Design Skill
 * 
 * Turns an accepted idea / SCAMPER angle into parametric CadQuery code
 * that can be exported as STEP/STL and 3D printed.
 * 
 * Focused on practical biomarker / sensor prototypes:
 * - electrode holders
 * - wristbands / mounts
 * - conductive-ink bases
 * - simple enclosures
 */

export interface HardwareDesignInput {
  idea: string;               // free text or SCAMPER angle text
  type?: "electrode-holder" | "wrist-mount" | "base-plate" | "enclosure" | "generic";
  dimensions?: {
    width?: number;   // mm
    height?: number;
    depth?: number;
    thickness?: number;
  };
  features?: string[];        // e.g. ["holes for screws", "cable channel", "clip"]
}

export interface HardwareDesignOutput {
  id: string;
  idea: string;
  type: string;
  cadquery_code: string;
  description: string;
  print_notes: string[];
  generated_at: string;
}

const TEMPLATES: Record<string, (input: HardwareDesignInput) => string> = {
  "electrode-holder": (input) => {
    const w = input.dimensions?.width ?? 40;
    const h = input.dimensions?.height ?? 20;
    const t = input.dimensions?.thickness ?? 3;
    return `
import cadquery as cq

# Electrode holder for conductive ink / dry electrodes
# Generated by Okaro hardware-design skill

result = (
    cq.Workplane("XY")
    .box(${w}, ${h}, ${t})
    .faces(">Z")
    .workplane()
    .rect(${w * 0.6}, ${h * 0.5}, forConstruction=True)
    .vertices()
    .hole(3)  # mounting holes
    .faces(">Z")
    .workplane()
    .center(0, 0)
    .slot2D(${w * 0.7}, 8, 90)  # cable / wire channel
    .cutThruAll()
)

show_object(result)
`.trim();
  },

  "wrist-mount": (input) => {
    const w = input.dimensions?.width ?? 50;
    const h = input.dimensions?.height ?? 30;
    const t = input.dimensions?.thickness ?? 4;
    return `
import cadquery as cq

# Simple wrist / arm mount for sensor
result = (
    cq.Workplane("XY")
    .box(${w}, ${h}, ${t})
    .edges("|Z")
    .fillet(2)
    .faces(">Z")
    .workplane()
    .rect(${w * 0.4}, ${h * 0.6})
    .cutThruAll()  # sensor window
    .faces(">Y")
    .workplane()
    .center(0, ${t / 2})
    .slot2D(12, 4)  # strap slot
    .cutThruAll()
)

show_object(result)
`.trim();
  },

  "base-plate": (input) => {
    const w = input.dimensions?.width ?? 60;
    const h = input.dimensions?.height ?? 60;
    const t = input.dimensions?.thickness ?? 2;
    return `
import cadquery as cq

# Flat base plate for conductive ink printing or sensor placement
result = (
    cq.Workplane("XY")
    .box(${w}, ${h}, ${t})
    .faces(">Z")
    .workplane()
    .rect(${w - 10}, ${h - 10}, forConstruction=True)
    .vertices()
    .hole(2.5)  # alignment / mounting holes
)

show_object(result)
`.trim();
  },

  "enclosure": (input) => {
    const w = input.dimensions?.width ?? 40;
    const h = input.dimensions?.height ?? 30;
    const d = input.dimensions?.depth ?? 15;
    return `
import cadquery as cq

# Simple snap-fit style enclosure shell
outer = cq.Workplane("XY").box(${w}, ${h}, ${d})
inner = cq.Workplane("XY").box(${w - 4}, ${h - 4}, ${d - 2}).translate((0, 0, 1))
result = outer.cut(inner)

show_object(result)
`.trim();
  },

  "generic": (input) => {
    const w = input.dimensions?.width ?? 40;
    const h = input.dimensions?.height ?? 30;
    const t = input.dimensions?.thickness ?? 5;
    return `
import cadquery as cq

# Generic parametric block — adapt as needed
result = (
    cq.Workplane("XY")
    .box(${w}, ${h}, ${t})
    .edges()
    .fillet(1)
)

show_object(result)
`.trim();
  },
};

function inferType(idea: string): HardwareDesignInput["type"] {
  const lower = idea.toLowerCase();
  if (lower.includes("eletrodo") || lower.includes("electrode") || lower.includes("tinta")) return "electrode-holder";
  if (lower.includes("pulso") || lower.includes("wrist") || lower.includes("braço") || lower.includes("mount")) return "wrist-mount";
  if (lower.includes("base") || lower.includes("placa") || lower.includes("plate")) return "base-plate";
  if (lower.includes("caixa") || lower.includes("enclosure") || lower.includes("case")) return "enclosure";
  return "generic";
}

export function generateHardwareDesign(input: HardwareDesignInput): HardwareDesignOutput {
  const type = input.type ?? inferType(input.idea);
  const template = TEMPLATES[type] ?? TEMPLATES["generic"];
  const code = template(input);

  return {
    id: `hw-${Date.now()}`,
    idea: input.idea,
    type,
    cadquery_code: code,
    description: `Parametric ${type} generated from idea: "${input.idea.slice(0, 120)}"`,
    print_notes: [
      "Use PLA or PETG, 0.2 mm layer height",
      "15-20% infill is usually enough",
      "Orient cable channels / holes facing up when possible",
      "Sand contact surfaces lightly if using conductive ink",
    ],
    generated_at: new Date().toISOString(),
  };
}

