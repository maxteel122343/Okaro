import fs from "node:fs";
import path from "node:path";
import nodemailer from "nodemailer";

export async function sendNotificationEmail(
  recipientEmail: string,
  paperName: string,
  attachments: string[] = []
): Promise<{ ok: boolean; message: string }> {
  const senderEmail = process.env.SMTP_EMAIL;
  const senderPassword = process.env.SMTP_PASSWORD;

  if (!senderEmail || !senderPassword) {
    return { ok: false, message: "SMTP credentials not configured." };
  }

  try {
    const transporter = nodemailer.createTransport({
      host: "smtp.gmail.com",
      port: 465,
      secure: true,
      auth: {
        user: senderEmail,
        pass: senderPassword,
      },
    });

    const validAttachments = attachments
      .filter((filePath) => fs.existsSync(filePath))
      .map((filePath) => ({
        filename: path.basename(filePath),
        path: filePath,
      }));

    await transporter.sendMail({
      from: senderEmail,
      to: recipientEmail,
      subject: `Paper Orchestra: ${paperName} is Complete!`,
      html: `
        <html>
        <body>
          <h2>🎻 Paper Orchestra Notification</h2>
          <p>Great news! Your paper has been successfully generated.</p>
          <p>Check the attachments for the final PDF and LaTeX source.</p>
          <hr>
          <p><small>Generated by Paper Orchestra AI</small></p>
        </body>
        </html>
      `,
      attachments: validAttachments,
    });

    return { ok: true, message: "Email sent successfully!" };
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return { ok: false, message: msg };
  }
}
